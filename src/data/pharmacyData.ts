// Approved 200 admin emails for "بوابة الفريق" (admin@bendaryph.com to admin200@bendaryph.com)
export function isApprovedTeamEmail(email: string): boolean {
  if (!email) return false;
  const clean = email.trim().toLowerCase();
  if (clean === 'admin@bendaryph.com') return true;
  const match = clean.match(/^admin([1-9]|[1-9][0-9]|1[0-9][0-9]|200)@bendaryph\.com$/);
  return !!match;
}
